def separate_and_correlate(df, unique_threshold=10, corr_threshold=0.5, multicollinearity_threshold=0.95, width=800, height=600):
    """
    Разделяет столбцы DataFrame на дискретные и непрерывные, вычисляет корреляцию Phi_K,
    выводит пары с корреляцией выше заданного порога и мультиколлинеарность,
    а также строит тепловую карту с помощью plotly.
    
    Parameters:
    - df: pandas DataFrame
    - unique_threshold: максимальное число уникальных значений для дискретных переменных (по умолчанию 10)
    - corr_threshold: порог для вывода значимых корреляций (по умолчанию 0.5)
    - multicollinearity_threshold: порог для мультиколлинеарности (по умолчанию 0.95)
    - width: ширина графика (по умолчанию 800)
    - height: высота графика (по умолчанию 600)
    
    Returns:
    - discrete_cols: список названий дискретных столбцов
    - continuous_cols: список названий непрерывных столбцов
    """
    discrete_cols = []
    continuous_cols = []

    for col in df.columns:
        dtype = df[col].dtype
        if dtype in ['object', 'category'] or str(dtype).startswith('period'):
            discrete_cols.append(col)
        elif pd.api.types.is_datetime64_any_dtype(dtype):
            discrete_cols.append(col)  # Считаем datetime дискретными
        elif pd.api.types.is_numeric_dtype(dtype):  # Устойчивая проверка числовых типов
            unique_count = df[col].nunique()
            if unique_count <= unique_threshold:
                discrete_cols.append(col)
            else:
                continuous_cols.append(col)
        else:
            print(f"Пропущена колонка {col} с типом {dtype} (неподдерживаемый тип).")

    print("Дискретные столбцы:", discrete_cols)
    print("Непрерывные столбцы:", continuous_cols)
    
    # Вычисление корреляции Phi_K
    numeric_cols = df.select_dtypes(include='number').columns.tolist()
    corr_matrix = df.phik_matrix(interval_cols=numeric_cols)
    
    # Удаляем столбец 'id', если он есть
    if 'id' in corr_matrix.columns:
        corr_matrix.drop('id', axis=0, inplace=True)
        corr_matrix.drop('id', axis=1, inplace=True)

    # Вывод корреляций выше заданного порога
    high_corr = corr_matrix[corr_matrix.abs() > corr_threshold]
    high_corr_pairs = high_corr.stack().reset_index()
    high_corr_pairs.columns = ['Variable 1', 'Variable 2', 'Correlation']
    high_corr_pairs = high_corr_pairs[high_corr_pairs['Variable 1'] != high_corr_pairs['Variable 2']]
    
    print(f"\nКорреляции больше {corr_threshold}:")
    if high_corr_pairs.empty:
        print("Нет корреляций выше заданного порога.")
    else:
        print(high_corr_pairs)

    multicollinearity = corr_matrix[corr_matrix.abs() > multicollinearity_threshold]
    multicollinearity_pairs = multicollinearity.stack().reset_index()
    multicollinearity_pairs.columns = ['Variable 1', 'Variable 2', 'Correlation']
    multicollinearity_pairs = multicollinearity_pairs[multicollinearity_pairs['Variable 1'] != multicollinearity_pairs['Variable 2']]
    
    print(f"\nМультиколлинеарность (корреляция больше {multicollinearity_threshold}):")
    if multicollinearity_pairs.empty:
        print("Нет мультиколлинеарности выше заданного порога.")
    else:
        print(multicollinearity_pairs)

    mask = np.triu(np.ones(corr_matrix.shape), k=1)  # k=1 убирает верхнюю правую часть

    fig = go.Figure(data=go.Heatmap(
        z=np.where(mask, np.nan, corr_matrix.values.round(2)),  # Нан вместо значений в верхней части
        x=corr_matrix.columns,
        y=corr_matrix.index,
        colorbar=dict(title='PhiK Correlation'),
        hovertemplate='%{x} - %{y}<br>Correlation: %{z}<extra></extra>'  # Настройка текста при наведении
    ))

    fig.update_layout(
        title='Тепловая карта PhiK',
        xaxis=dict(title='Переменные', tickangle=-45),
        yaxis=dict(title='Переменные'),
        width=width,
        height=height
    )

    fig.show()
    
    return discrete_cols, continuous_cols

