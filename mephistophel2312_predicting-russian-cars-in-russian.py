# Функция для разбора номера
def parse_plate(plate):
    if not isinstance(plate, str) or not plate:
        return None, None, None
    # Регулярное выражение для формата, например, X059CP797 или A123AA777
    match = re.match(r'^([А-ЯA-Z]{1,3})(\d{3})([А-ЯA-Z]{1,3})(\d{2,3})$', plate)
    if match:
        series = match.group(1) + match.group(3)  # Объединяем буквы (например, XCP или AAA)
        number = int(match.group(2))  # Цифры (например, 059)
        region = match.group(4)  # Код региона (например, 797 или 777)
        return series, number, region
    return None, None, None

# Функция для проверки, соответствует ли номер условиям региона
def is_plate_in_region(plate, region_codes):
    series, number, region = parse_plate(plate)
    if series is None or number is None or region is None:
        return False
    for code, (start, end), reg in GOVERNMENT_CODES:
        if reg in region_codes and series == code and start <= number <= end and region == reg:
            return True
    return False

