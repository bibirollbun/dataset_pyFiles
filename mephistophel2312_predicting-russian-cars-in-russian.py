# Функция для определения сезона
def get_season(month):
    if pd.isna(month):
        return 'Неизвестно'
    if month in [12, 1, 2]:
        return 'Зима'
    elif month in [3, 4, 5]:
        return 'Весна'
    elif month in [6, 7, 8]:
        return 'Лето'
    else:
        return 'Осень'

