def summarize(DataFrame):
    summary = pd.DataFrame()
    summary['type'] = DataFrame.dtypes
    summary['sum_nan'] = DataFrame.isna().sum()
    summary['%_nan'] = round(DataFrame.isna().sum() / len(DataFrame) * 100, 2)
    summary['unique'] = DataFrame.apply(lambda x: ", ".join(map(str, x.unique())) if len(x.unique()) <= 8 else len(x.unique()))
    summary['mode'] = DataFrame.apply(lambda x: x.mode().iloc[0] if not x.mode().empty else '-')
    
    # Проверяем, что тип данных числовой (int или float) и НЕ булевый
    def is_numeric_non_bool(dtype):
        return pd.api.types.is_numeric_dtype(dtype) and not pd.api.types.is_bool_dtype(dtype)

    # Применяем числовые статистики только к подходящим столбцам
    summary['max'] = DataFrame.apply(lambda x: x.max() if is_numeric_non_bool(x) else '-')
    summary['75_quantile'] = DataFrame.apply(lambda x: round(x.quantile(0.75), 2) if is_numeric_non_bool(x) else '-')
    summary['median'] = DataFrame.apply(lambda x: round(x.median(), 2) if is_numeric_non_bool(x) else '-')
    summary['25_quantile'] = DataFrame.apply(lambda x: round(x.quantile(0.25), 2) if is_numeric_non_bool(x) else '-')
    summary['min'] = DataFrame.apply(lambda x: x.min() if is_numeric_non_bool(x) else '-')
    summary['mean'] = DataFrame.apply(lambda x: round(x.mean(), 2) if is_numeric_non_bool(x) else '-')
    summary['standard_deviation'] = DataFrame.apply(lambda x: round(x.std(), 2) if is_numeric_non_bool(x) else '-')

    # Сортировка по type
    summary['type'] = summary['type'].astype(str)
    type_order = ['int64', 'float64', 'bool', 'category', 'datetime64[ns]', 'object']
    summary['type'] = pd.Categorical(summary['type'], categories=type_order, ordered=True)
    summary = summary.sort_values(by='type')
    summary['type'] = summary['type'].astype(str)

    return summary

# Функция для преобразования названий столбцов и значений в змеиной стиль
def snake(df):
    # Функция для преобразования строки в змеиной стиль (для значений)
    def to_snake_case_value(value):
        if isinstance(value, str):  # Проверяем, является ли значение строкой
            value = re.sub(r'[^\w\s]', '', value)  # Удаляем все символы, кроме букв, цифр и пробелов
            value = value.replace(' ', '_')  # Заменяем пробелы на нижние подчеркивания
            return value.lower()  # Приводим к нижнему регистру
        return value  # Возвращаем значение без изменений, если это не строка

    # Функция для преобразования названий столбцов
    def to_snake_case_column(name):
        # Удаляем специальные символы, кроме букв, цифр и пробелов
        name = re.sub(r'[^\w\s]', '', name)
        
        
        # 1. Вставляем _ перед заглавной буквой, если перед ней строчная
        # 2. Вставляем _ между строчной и группой заглавных букв
        # 3. Вставляем _ перед заглавной, если за ней следует строчная
        result = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name)  # строчная -> заглавная
        result = re.sub(r'([A-Z])([A-Z][a-z])', r'\1_\2', result)  # заглавная -> заглавная+строчная
        result = result.replace(' ', '_').lower()  # Заменяем пробелы на _ и приводим к нижнему регистру
        result = re.sub(r'_+', '_', result)  # Удаляем множественные подчеркивания
        result = result.strip('_')  # Удаляем подчеркивания в начале и конце
        return result

    # Преобразуем названия столбцов
    df.columns = [to_snake_case_column(col) for col in df.columns]
    
    # Применяем функцию ко всем значениям в DataFrame
    df = df.applymap(to_snake_case_value)
    
    return df

