def evaluate_ml_models(X, y, dataset_name, target_name):
    """Evaluate multiple ML models using cross-validation"""

    if y is None or len(np.unique(y)) < 2:
        print(f"âš ï¸� Skipping {dataset_name} - {target_name}: insufficient target variation")
        return None

    # Remove NaN targets
    valid_idx = ~np.isnan(y)
    X_clean = X[valid_idx]
    y_clean = y[valid_idx]

    if len(X_clean) < 10:
        print(f"âš ï¸� Skipping {dataset_name} - {target_name}: too few samples after cleaning")
        return None

    # Scale features
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X_clean)

    # Define models
    models = {
        'Linear Regression': LinearRegression(),
        'Ridge Regression': Ridge(alpha=1.0),
        'Lasso Regression': Lasso(alpha=0.1),
        'Random Forest': RandomForestRegressor(n_estimators=100, random_state=42),
        'Gradient Boosting': GradientBoostingRegressor(n_estimators=100, random_state=42)
    }

    # Cross-validation
    kf = KFold(n_splits=5, shuffle=True, random_state=42)
    results = {}

    for name, model in models.items():
        try:
            # Calculate RMSE using cross-validation
            rmse_scores = -cross_val_score(model, X_scaled, y_clean,
                                         cv=kf, scoring='neg_root_mean_squared_error')
            r2_scores = cross_val_score(model, X_scaled, y_clean, cv=kf, scoring='r2')

            results[name] = {
                'RMSE_mean': rmse_scores.mean(),
                'RMSE_std': rmse_scores.std(),
                'R2_mean': r2_scores.mean(),
                'R2_std': r2_scores.std()
            }

            print(f"   {name}: RMSE = {rmse_scores.mean():.4f} Â± {rmse_scores.std():.4f}, "
                  f"RÂ² = {r2_scores.mean():.4f} Â± {r2_scores.std():.4f}")

        except Exception as e:
            print(f"   â�Œ {name} failed: {e}")

    return results

