def create_dnn_model(input_dim, learning_rate=0.001):
    """Create a Deep Neural Network model"""
    model = keras.Sequential([
        layers.Dense(256, activation='relu', input_shape=(input_dim,)),
        layers.BatchNormalization(),
        layers.Dropout(0.3),

        layers.Dense(128, activation='relu'),
        layers.BatchNormalization(),
        layers.Dropout(0.3),

        layers.Dense(64, activation='relu'),
        layers.Dropout(0.2),

        layers.Dense(32, activation='relu'),
        layers.Dropout(0.2),

        layers.Dense(1)  # Output layer for regression
    ])

    model.compile(
        optimizer=keras.optimizers.Adam(learning_rate=learning_rate),
        loss='mse',
        metrics=['mae', 'mse']
    )

    return model

def create_cnn_model(input_dim, learning_rate=0.001):
    """Create a 1D CNN model for spectral data"""
    model = keras.Sequential([
        layers.Reshape((input_dim, 1), input_shape=(input_dim,)),

        layers.Conv1D(64, 3, activation='relu', padding='same'),
        layers.BatchNormalization(),
        layers.MaxPooling1D(2),

        layers.Conv1D(128, 3, activation='relu', padding='same'),
        layers.BatchNormalization(),
        layers.MaxPooling1D(2),

        layers.Conv1D(256, 3, activation='relu', padding='same'),
        layers.BatchNormalization(),
        layers.GlobalAveragePooling1D(),

        layers.Dense(128, activation='relu'),
        layers.Dropout(0.3),

        layers.Dense(64, activation='relu'),
        layers.Dropout(0.2),

        layers.Dense(1)
    ])

    model.compile(
        optimizer=keras.optimizers.Adam(learning_rate=learning_rate),
        loss='mse',
        metrics=['mae', 'mse']
    )

    return model

def evaluate_dl_models(X, y, dataset_name, target_name):
    """Evaluate Deep Learning models"""

    if y is None or len(np.unique(y)) < 2:
        return None

    # Remove NaN targets
    valid_idx = ~np.isnan(y)
    X_clean = X[valid_idx]
    y_clean = y[valid_idx]

    if len(X_clean) < 20:
        return None

    # Scale features and targets
    x_scaler = StandardScaler()
    X_scaled = x_scaler.fit_transform(X_clean)

    y_scaler = StandardScaler()
    y_scaled = y_scaler.fit_transform(y_clean.reshape(-1, 1)).flatten()

    # Split data
    X_train, X_test, y_train, y_test = train_test_split(
        X_scaled, y_scaled, test_size=0.2, random_state=42
    )

    results = {}
    models = {
        'DNN': create_dnn_model(X_scaled.shape[1]),
        'CNN': create_cnn_model(X_scaled.shape[1])
    }

    for model_name, model in models.items():
        try:
            # Early stopping
            early_stopping = keras.callbacks.EarlyStopping(
                monitor='val_loss', patience=10, restore_best_weights=True
            )

            # Train model
            history = model.fit(
                X_train, y_train,
                validation_data=(X_test, y_test),
                epochs=100,
                batch_size=32,
                callbacks=[early_stopping],
                verbose=0
            )

            # Predict and inverse transform
            y_pred_scaled = model.predict(X_test).flatten()
            y_pred = y_scaler.inverse_transform(y_pred_scaled.reshape(-1, 1)).flatten()
            y_test_original = y_scaler.inverse_transform(y_test.reshape(-1, 1)).flatten()

            # Calculate metrics
            rmse = np.sqrt(mean_squared_error(y_test_original, y_pred))
            mae = mean_absolute_error(y_test_original, y_pred)
            r2 = r2_score(y_test_original, y_pred)

            results[model_name] = {
                'RMSE': rmse,
                'MAE': mae,
                'R2': r2,
                'history': history
            }

            print(f"   {model_name}: RMSE = {rmse:.4f}, MAE = {mae:.4f}, RÂ² = {r2:.4f}")

        except Exception as e:
            print(f"   â�Œ {model_name} failed: {e}")

    return results

