def preprocess_spectra_upgraded(X, method='baseline_snv_airpls', deriv_order=1):
    """Applies advanced preprocessing to spectral data with optimized parameters."""
    X_processed = np.asarray(X, dtype=float)
    if method == 'baseline_snv_airpls':
        for i in range(X_processed.shape[0]):
            baseline, _ = airpls(X_processed[i, :])
            corrected_spectrum = X_processed[i, :] - baseline
            mean, std = corrected_spectrum.mean(), corrected_spectrum.std()
            if std > 1e-8:
                X_processed[i, :] = (corrected_spectrum - mean) / std
            else:
                X_processed[i, :] = corrected_spectrum - mean
    elif method == 'derivative':
        # Increased window_length for more aggressive smoothing
        X_processed = signal.savgol_filter(X, window_length=35, polyorder=2, deriv=deriv_order, axis=1)
    return X_processed

