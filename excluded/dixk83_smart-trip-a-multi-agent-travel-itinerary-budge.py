class SessionMemory:
    """
    SessionMemory
    -------------
    A lightweight in-memory storage component used to preserve user-specific
    information across multiple agent calls.

    In this project, the memory stores user preferences such as:
        - Preferred cuisine (e.g., "halal")
        - Travel style (e.g., "family-friendly")
        - Activity interests (e.g., "museums")

    This class demonstrates the concept of:
        ✔ Session state management
        ✔ Memory sharing across sequential agents
        ✔ Context persistence throughout the workflow

    While simple, it mirrors how more advanced agent systems maintain
    contextual continuity between steps.
    """

    def __init__(self):
        """
        Initialize a new SessionMemory instance.

        user_prefs:
            A dictionary that stores user-defined preferences.
            Example:
                {
                    "food": "halal",
                    "type": "family-friendly",
                    "likes": "museums"
                }
        """
        self.user_prefs: dict = {}

    def save_prefs(self, prefs: dict) -> None:
        """
        Save or update the user's preferences.

        Parameters
        ----------
        prefs : dict
            A dictionary containing preference key-value pairs.
            New entries will be added, and existing entries will be updated.

        Example
        -------
        memory.save_prefs({
            "food": "halal",
            "likes": "museums"
        })
        """
        self.user_prefs.update(prefs)

    def get_prefs(self) -> dict:
        """
        Retrieve the current user preferences stored in memory.

        Returns
        -------
        dict
            The dictionary of stored user preferences, or an empty dict if none exist.

        Example
        -------
        prefs = memory.get_prefs()
        """
        return self.user_prefs




def estimate_trip_cost(itinerary: dict) -> dict:
    """
    estimate_trip_cost
    ------------------
    A custom "tool" used by the BudgetAgent to calculate a rough cost estimate
    for a travel itinerary. This demonstrates the required concept of tool usage
    in an agentic workflow.

    Parameters
    ----------
    itinerary : dict
        A structured itinerary generated by the PlannerAgent.
        Expected format:
        {
            "city": "Montreal",
            "days": [
                {
                    "day": 1,
                    "activities": [...],
                    "meals": [...]
                },
                ...
            ]
        }

    Cost Model (Simplified Assumptions)
    -----------------------------------
    • Lodging:  $80 per day  
    • Activities: $20 per activity  
    • Meals: $15 per meal  

    These values intentionally remain simple so that the tool
    is easy to understand and reproducible.

    Returns
    -------
    dict
        A dictionary containing:
        {
            "estimated_cost": float,     # total trip cost
            "breakdown": {
                "lodging": float,
                "activities": float,
                "meals": float
            }
        }

    Example
    -------
    cost_info = estimate_trip_cost(itinerary)
    print(cost_info["estimated_cost"])
    """

    # ---- Cost assumptions (can be tuned based on travel scenario) ----
    daily_lodging_cost = 80.0      # Cost per day for lodging
    activity_cost = 20.0           # Cost per activity
    meal_cost = 15.0               # Cost per meal

    # ---- Extract counts from itinerary structure ----
    num_days = len(itinerary.get("days", []))
    num_activities = sum(len(day.get("activities", [])) 
                         for day in itinerary.get("days", []))
    num_meals = sum(len(day.get("meals", [])) 
                     for day in itinerary.get("days", []))

    # ---- Calculate cost components ----
    total_lodging = num_days * daily_lodging_cost
    total_activities = num_activities * activity_cost
    total_meals = num_meals * meal_cost

    # ---- Total estimated cost ----
    total_cost = total_lodging + total_activities + total_meals

    # ---- Return detailed breakdown ----
    return {
        "estimated_cost": total_cost,
        "breakdown": {
            "lodging": total_lodging,
            "activities": total_activities,
            "meals": total_meals,
        },
    }




def planner_agent(city: str, days: int, budget: float, memory: SessionMemory) -> dict:
    """
    PlannerAgent
    ------------
    The PlannerAgent is responsible for generating a *draft itinerary*
    based on user inputs such as destination city, number of days,
    and preferences stored in SessionMemory.

    This agent represents the **first step** in the multi-agent pipeline and
    demonstrates:
        • Reading contextual information from memory
        • Producing structured output usable by other agents
        • Sequential agent handoff behavior

    In a fully featured system, this agent would call an LLM (e.g., Gemini)
    to produce richly detailed itineraries. However, since outbound internet
    is disabled in Kaggle competition environments, the itinerary below is
    generated using deterministic Python logic while still exercising the
    agent orchestration pattern.

    Parameters
    ----------
    city : str
        Destination city for the trip.

    days : int
        Number of days for the itinerary.

    budget : float
        Total budget for the trip (not directly used here but included for extensibility).

    memory : SessionMemory
        Object storing user preferences such as:
            {"food": "halal", "likes": "museums"}

    Returns
    -------
    dict
        A structured itinerary of the form:
        {
            "city": city,
            "days": [
                {
                    "day": 1,
                    "activities": [...],
                    "meals": [...]
                },
                ...
            ]
        }

    Notes
    -----
    Downstream agents such as BudgetAgent and SummaryAgent consume this output.
    """

    print("[PlannerAgent] Creating draft itinerary...")

    # Retrieve user preferences from memory to personalize activities/meals
    prefs = memory.get_prefs()

    # Initialize itinerary structure
    itinerary = {
        "city": city,
        "days": []
    }

    # Build a simple daily plan
    for day_num in range(1, days + 1):

        # Basic activity set
        activities = [
            f"Explore a popular museum in {city}",
            f"Walk around the historic downtown area of {city}",
        ]

        # Add preference-based activity if available
        if prefs.get("likes"):
            activities.append(f"Spend extra time on {prefs['likes']}-related experiences")

        # Meal selection based on preference
        meals = [
            f"Try a local restaurant (preference: {prefs.get('food', 'any cuisine')})"
        ]

        itinerary["days"].append({
            "day": day_num,
            "activities": activities,
            "meals": meals,
        })

    return itinerary




def budget_agent(itinerary: dict, budget: float, memory: SessionMemory):
    """
    BudgetAgent
    -----------
    The BudgetAgent is responsible for validating the draft itinerary
    against the user's budget and simplifying the plan if it is too expensive.

    This agent demonstrates:
        • Integration of a custom tool (`estimate_trip_cost`) to perform
          numeric computation beyond pure LLM logic.
        • Simple "reasoning" over tool outputs (comparing cost vs. budget).
        • Modification of the shared itinerary before passing it downstream.

    Workflow
    --------
    1. Call `estimate_trip_cost(itinerary)` to compute:
           - Total estimated cost
           - Lodging / activities / meals breakdown
    2. If the total cost is within the user's budget:
           - Leave the itinerary unchanged.
    3. If the total cost exceeds the budget:
           - Apply a simple rule: reduce one activity per day (if possible).
           - Recalculate the cost after simplification.

    Parameters
    ----------
    itinerary : dict
        The structured itinerary created by the PlannerAgent.

    budget : float
        The user's total budget for the trip.

    memory : SessionMemory
        Session memory object. Included here for extensibility and to
        emphasize that agents share access to common state, even if this
        specific version does not read from it.

    Returns
    -------
    tuple
        (updated_itinerary, cost_info)

        updated_itinerary : dict
            The possibly simplified itinerary that now better fits the budget.

        cost_info : dict
            The output from `estimate_trip_cost`, e.g.:
            {
                "estimated_cost": float,
                "breakdown": {
                    "lodging": float,
                    "activities": float,
                    "meals": float
                }
            }
    """

    print("[BudgetAgent] Estimating cost and adjusting itinerary if needed...")

    # 1) Compute the cost of the current itinerary using the custom tool.
    cost_info = estimate_trip_cost(itinerary)
    total = cost_info["estimated_cost"]

    # 2) If the cost is already within budget, no changes are required.
    if total <= budget:
        print(f"[BudgetAgent] Total cost {total:.2f} is within budget {budget:.2f}.")
        return itinerary, cost_info

    # 3) If over budget, apply a simple heuristic: reduce one activity per day.
    print(f"[BudgetAgent] Over budget: {total:.2f} > {budget:.2f}. Simplifying plan...")

    for day in itinerary.get("days", []):
        activities = day.get("activities", [])
        # Keep only the first activity if there are multiple
        if len(activities) > 1:
            day["activities"] = activities[:1]

    # 4) Recalculate the cost after simplification to reflect the new plan.
    cost_info = estimate_trip_cost(itinerary)
    new_total = cost_info["estimated_cost"]
    print(f"[BudgetAgent] New estimated cost after simplification: {new_total:.2f}")

    return itinerary, cost_info




def summary_agent(itinerary: dict, cost_info: dict, memory: SessionMemory) -> str:
    """
    SummaryAgent
    ------------
    The SummaryAgent is the final step in the multi-agent workflow. It takes the
    enriched itinerary and cost information from previous agents and produces a
    user-friendly, well-structured trip summary.

    This version uses Gemini (via `gemini_model.generate_content`) to:
        • Rewrite a draft text summary into a more polished itinerary
        • Improve clarity, structure, and presentation
        • Preserve all factual details while enhancing readability

    In contexts where external API calls are not allowed (e.g., some Kaggle
    competition environments without internet access), this agent design still
    demonstrates how an LLM can be integrated as part of an agent system,
    even if the actual call must be disabled or replaced.

    Parameters
    ----------
    itinerary : dict
        Structured trip plan produced by the PlannerAgent and possibly updated
        by the BudgetAgent. Expected format:
        {
            "city": "Montreal",
            "days": [
                {
                    "day": 1,
                    "activities": [...],
                    "meals": [...]
                },
                ...
            ]
        }

    cost_info : dict
        Output from `estimate_trip_cost`, including total and breakdown:
        {
            "estimated_cost": float,
            "breakdown": {
                "lodging": float,
                "activities": float,
                "meals": float
            }
        }

    memory : SessionMemory
        Session memory containing user preferences, which are included in the
        final summary for transparency and personalization.

    Returns
    -------
    str
        A polished, human-readable itinerary text generated by Gemini that can
        be shown directly to the end user.

    Notes
    -----
    If Gemini is not available in the execution environment, this function
    would need to be adapted to return `draft_summary` directly, or use a
    non-LLM formatter instead.
    """

    print("[SummaryAgent] Creating final user-friendly summary with Gemini...")

    # Retrieve preferences so we can show that the plan reflects user context.
    prefs = memory.get_prefs()

    # -------------------------------------------------------------
    # 1) Build a simple draft summary (plain text, deterministic).
    #    This draft is then passed to Gemini for rewriting.
    # -------------------------------------------------------------
    lines = []
    lines.append(f"Trip plan for {itinerary['city']}")
    lines.append("")

    for day in itinerary.get("days", []):
        lines.append(f"Day {day['day']}:")
        for act in day.get("activities", []):
            lines.append(f"  - Activity: {act}")
        for meal in day.get("meals", []):
            lines.append(f"  - Meal: {meal}")
        lines.append("")

    # Add cost details
    lines.append("Estimated cost:")
    lines.append(f"  - Total: {cost_info['estimated_cost']:.2f}")
    for k, v in cost_info.get("breakdown", {}).items():
        lines.append(f"  - {k.capitalize()}: {v:.2f}")

    # Include user preferences as part of the context
    if prefs:
        lines.append("")
        lines.append(f"User preferences: {prefs}")

    draft_summary = "\n".join(lines)

    # -------------------------------------------------------------
    # 2) Ask Gemini to rewrite the draft into a polished itinerary.
    # -------------------------------------------------------------
    prompt = f"""
You are a friendly travel planning assistant.

Rewrite the following draft trip plan into a clear, concise, and well-formatted itinerary for the user.
Keep ALL factual details (city, days, activities, meals, and cost breakdown), but improve the wording
and organization. Use headings and bullet points where appropriate.

Draft plan:
{draft_summary}
"""

    # `gemini_model` is assumed to be created and configured earlier, e.g.:
    #   gemini_model = genai.GenerativeModel("gemini-2.0-flash")
    response = gemini_model.generate_content(prompt)

    # Return the text body produced by Gemini
    return response.text



def run_travel_concierge(city: str,
                         days: int,
                         budget: float,
                         prefs: dict) -> str:
    """
    run_travel_concierge
    --------------------
    Top-level orchestration function for the AI Travel Concierge system.

    This function ties together the three main agents in a sequential
    multi-agent pipeline:

        1. PlannerAgent  → creates a draft itinerary
        2. BudgetAgent   → validates and adjusts the itinerary to fit the budget
        3. SummaryAgent  → produces the final user-facing trip summary

    It also demonstrates how shared session memory is initialized and passed
    through the pipeline to keep user preferences available to each agent.

    Parameters
    ----------
    city : str
        Destination city for the trip (e.g., "Montreal").

    days : int
        Number of days for the trip (e.g., 2 for a weekend getaway).

    budget : float
        Total budget for the trip, used by BudgetAgent to adjust the plan.

    prefs : dict
        User preferences to be stored in session memory, for example:
            {
                "food": "halal",
                "type": "family-friendly",
                "likes": "museums"
            }

    Returns
    -------
    str
        Final, user-friendly itinerary text generated by the SummaryAgent.

    Example
    -------
    result = run_travel_concierge(
        city="Montreal",
        days=2,
        budget=400.0,
        prefs={"food": "halal", "type": "family-friendly", "likes": "museums"}
    )
    print(result)
    """

    print("[Orchestrator] Starting AI Travel Concierge workflow...")
    print(f"[Orchestrator] City={city}, Days={days}, Budget={budget}, Prefs={prefs}")

    # 1) Initialize session memory and store user preferences
    memory = SessionMemory()
    memory.save_prefs(prefs)

    # 2) PlannerAgent: create a draft itinerary based on city, days, and preferences
    itinerary = planner_agent(city, days, budget, memory)

    # 3) BudgetAgent: estimate cost and adjust itinerary to fit within the budget
    itinerary, cost_info = budget_agent(itinerary, budget, memory)

    # 4) SummaryAgent: generate the final formatted trip plan
    final_output = summary_agent(itinerary, cost_info, memory)

    print("[Orchestrator] Workflow completed.")
    return final_output



