retry_config = types.HttpRetryOptions(
    attempts=5,  # Maximum retry attempts
    exp_base=7,  # Delay multiplier
    initial_delay=1,
    http_status_codes=[429, 500, 503, 504],  # Retry on these HTTP errors
)


research_agent = LlmAgent(
    name="KozhikodeFoodResearchAgent",
    model=Gemini(model="gemini-2.5-flash-lite", retry_options=retry_config),
    instruction="""You are a specialized research agent focused on the 'LocalFood AI â€“ Kozhikode' project. 
Your primary goal is to gather foundational data for an AI-powered food finder that assists tourists 
in the Malabar region.

Specifically, use the google_search tool to find 2-3 pieces of relevant, current information on:
1.  **Authentic Malabar traditional dishes** (e.g., specific recipes, history, or cultural significance).
2.  **Highly-rated restaurants or hotels in Kozhikode** known for serving these traditional foods (with a focus on Google review ratings).
3.  **Potential competitors or similar 'local food finder' solutions** in the South Indian market.

Present the findings concisely, ensuring all information is accompanied by clear, web-based citations.""",
    tools=[google_search],
    output_key="kozhikode_food_research_findings", # The result of this agent will be stored in the session state with this key.
)
print("âœ… research_agent created.")



# --- Summarizer Agent Definition for LocalFood AI â€“ Kozhikode ---

# Summarizer Agent: Its job is to summarize the text it receives.
# It expects the research findings to be passed in using the key 
# 'kozhikode_food_research_findings' from the research agent.
summarizer_agent = LlmAgent(
    name="SummarizerAgent",
    model=Gemini(model="gemini-2.5-flash-lite", retry_options=retry_config),
    # The instruction is modified to request a bulleted list for a clear output format,
    # and to explicitly look for the output key generated by the research agent.
    instruction="""Read the provided research findings from the Kozhikode food project: 
{kozhikode_food_research_findings}

Create a concise summary as a bulleted list with 3-5 key points relevant to the
development of the 'LocalFood AI â€“ Kozhikode' food finder application. Focus on 
actionable insights about dishes, highly-rated locations, and competitor analysis.""",
    output_key="final_summary", # The output key is set to 'final_summary' as requested.
)
print("âœ… summarizer_agent created.")


# Root Coordinator: Orchestrates the workflow by calling the sub-agents as tools.
root_agent = LlmAgent(
    name="ResearchCoordinator",
    model=Gemini(model="gemini-2.5-flash-lite", retry_options=retry_config),
    # This instruction tells the root agent HOW to use its tools (which are the other agents).
    instruction="""You are a research coordinator for the 'LocalFood AI â€“ Kozhikode' project. 
Your goal is to answer the user's query by orchestrating a workflow:

1. First, you MUST call the `KozhikodeFoodResearchAgent` tool to find relevant information on the topic provided by the user.
2. Next, after receiving the research findings, you MUST call the `SummarizerAgent` tool to create a concise summary.
3. Finally, present the final summary clearly to the user as your response.""",
    # We wrap the sub-agents in `AgentTool` to make them callable tools for the root agent.
    tools=[
        AgentTool(research_agent),
        AgentTool(summarizer_agent)
    ],
)
print("âœ… root_agent created.")


