class FlashcardAgent:
    """Responsible for generating flashcards based on a topic using the LLM agent."""
    def __init__(self, llm_agent: MockLLMAgent):
        self.llm = llm_agent

    def run(self, topic: str, n_cards: int = DEFAULT_FLASHCARD_COUNT) -> List[Flashcard]:
        """Generates a specified number of flashcards."""
        cards = []
        for i in range(n_cards):
            q = f"Q{i+1}: Define the core principle of **{topic}**."
            a = self.llm.explain(topic, level='short summary')
            # Flashcard is created with default SRS fields
            cards.append(Flashcard(question=q, answer=a))
        logger.debug(f"Generated {n_cards} flashcards for {topic}")
        return cards

# NEW: SRSAgent (Spaced Repetition System Agent)

class SRSAgent:
    """
    Implements the core logic of the SuperMemo-2 (SM-2) Spaced Repetition System.
    Calculates the next review interval based on recall quality.
    """
    def update_card(self, card: Flashcard, quality_of_recall: int) -> Flashcard:
        """
        Updates the card's ease, interval, and repetitions based on the user's recall quality (0-5).
        """
        if not (0 <= quality_of_recall <= 5):
            raise ValueError("Quality of recall must be between 0 and 5.")

        # --- 1. Update Repetitions (n) and Interval Reset ---
        if quality_of_recall < 3:
            # Failed or hesitant recall (Score 0, 1, or 2)
            card.repetitions = 0
            # Reset interval to 1 day (review tomorrow)
            card.interval = 1 
        else:
            # Successful recall (Score 3, 4, or 5)
            card.repetitions += 1
            
        # --- 2. Update Ease Factor (EF) ---
        # SM-2 formula: EF = EF + (0.1 - (5 - quality) * (0.08 + (5 - quality) * 0.02))
        card.ease = card.ease + (0.1 - (5 - quality_of_recall) * (0.08 + (5 - quality_of_recall) * 0.02))
        
        # Ensure EF never drops below 1.3
        card.ease = max(1.3, card.ease)

        # --- 3. Calculate Next Interval (I) ---
        if card.repetitions == 1:
            card.interval = 1
        elif card.repetitions == 2:
            card.interval = 6
        elif card.repetitions > 2:
            # I(n) = I(n-1) * EF
            card.interval = round(card.interval * card.ease)
        # If repetitions is 0 and recall was bad (<3), interval is already set to 1 in step 1.
            
        return card

# Coordinator

class StudyCoordinator:
    """
    The main orchestrator. Coordinates parallel execution of content agents
    and sequential execution of the LLM agent, storing results in a session.
    """
    def __init__(self, session_service: InMemorySessionService):
        # Dependency Injection of services/agents
        self.sessions = session_service
        self.llm = MockLLMAgent()
        self.search_agent = ContentSearchAgent()
        self.flashcard_agent = FlashcardAgent(self.llm)
        self.srs_agent = SRSAgent() # NEW: Initialize SRS Agent

    def create_or_get_session(self, user_id: str, metadata: Optional[Dict[str, Any]] = None) -> str:
        """Handles session creation (or retrieval in a full system)."""
        return self.sessions.create_session(user_id, metadata)

    def _execute_parallel_agents(self, topics: List[str]) -> Dict[str, Dict[str, Union[List[Resource], List[Flashcard]]]]:
        """Executes the search and flashcard agents in parallel for performance."""
        results = {"resources": {}, "flashcards": {}}
        
        # Use ThreadPoolExecutor for concurrent tasks (I/O and light generation)
        with concurrent.futures.ThreadPoolExecutor(max_workers=MAX_WORKERS) as ex:
            # 1. Schedule all resource search tasks
            future_to_topic_search = {ex.submit(self.search_agent.run, t): t for t in topics}
            # 2. Schedule all flashcard generation tasks
            future_to_topic_flash = {ex.submit(self.flashcard_agent.run, t, DEFAULT_FLASHCARD_COUNT): t for t in topics}

            # 3. Collect results for resources and handle errors
            for fut in concurrent.futures.as_completed(future_to_topic_search):
                topic = future_to_topic_search[fut]
                try:
                    results['resources'][topic] = fut.result()
                    logger.info(f"Successfully retrieved resources for {topic}")
                except Exception as e:
                    results['resources'][topic] = []
                    logger.error(f"Error fetching resources for {topic}: {e}")

            # 4. Collect results for flashcards and handle errors
            for fut in concurrent.futures.as_completed(future_to_topic_flash):
                topic = future_to_topic_flash[fut]
                try:
                    results['flashcards'][topic] = fut.result()
                    logger.info(f"Successfully generated flashcards for {topic}")
                except Exception as e:
                    results['flashcards'][topic] = []
                    logger.error(f"Error generating flashcards for {topic}: {e}")

        return results

    def _execute_sequential_llm_tasks(self, topics: List[str]) -> Dict[str, Dict[str, Any]]:
        """Executes LLM tasks (quizzes and info queries) sequentially by topic."""
        results = {"quizzes": {}, "informative_queries": {}}

        for topic in topics:
            # Quiz Generation
            quiz = self.llm.generate_quiz(topic, n_questions=DEFAULT_QUIZ_COUNT)
            results['quizzes'][topic] = quiz

            # Informative Queries (Prerequisites, Key Concepts, etc.)
            answers = {}
            for qt in INFORMATIVE_QUERY_TYPES:
                answers[qt] = self.llm.answer_query(topic, qt)
            results['informative_queries'][topic] = answers
            
            logger.debug(f"Completed sequential LLM tasks for {topic}")

        return results

    def plan_for(self, session_id: str, topics: List[str], weekly_hours: int = 5) -> Dict[str, Any]:
        """
        Generates a comprehensive study plan by coordinating parallel and sequential agents.
        """
        start_time = time.time()
        logger.info(f"Starting plan generation for session {session_id} covering {len(topics)} topics.")

        # 1. Update session state
        self.sessions.set_state(session_id, 'topics', topics)
        self.sessions.set_state(session_id, 'weekly_hours', weekly_hours)

        # 2. Execute agents in parallel (Search & Flashcard)
        parallel_results = self._execute_parallel_agents(topics)

        # 3. Execute agents sequentially (Quizzes & Informative Queries)
        sequential_results = self._execute_sequential_llm_tasks(topics)

        # 4. Merge all results
        plan_results = {**parallel_results, **sequential_results}

        # 5. Final session update and logging
        self.sessions.set_state(session_id, 'last_plan', plan_results)
        end_time = time.time()
        logger.info(f"Plan generation complete in {end_time - start_time:.2f} seconds.")
        
        return plan_results

