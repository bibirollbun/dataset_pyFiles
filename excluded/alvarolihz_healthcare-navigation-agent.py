def tool_search_centers(specialty: str, location: str, k: int = 3) -> List[str]:
    """Simulate search for medical centers in a city, prioritizing by specialty."""
    loc = ensure_location_known(location)
    pool = SIMULATED_CENTERS.get(loc, [])
    # Simple deterministic ranking: prioritize names with specialty keywords
    keywords = {
        "Cardiology": ["Cardio", "ClÃ­nica", "Hospital"],
        "Pulmonology": ["Respir", "Hospital", "Centro"],
        "General Medicine": ["Centro", "Consultorio", "ClÃ­nica"],
    }
    hints = keywords.get(specialty, ["Centro", "ClÃ­nica"])
    scored = []
    for name in pool:
        score = sum(1 for h in hints if h.lower() in name.lower())
