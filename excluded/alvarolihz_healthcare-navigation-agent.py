# 6. Agent core
# ============================================
def classify_specialty(symptoms: List[str]) -> str:
    # Take the first known match; if none, use DEFAULT_SPECIALTY
    for s in symptoms:
        key = s.strip().lower()
        if key in SYMPTOM_TO_SPECIALTY:
            return SYMPTOM_TO_SPECIALTY[key]
    return DEFAULT_SPECIALTY

def recommend_agent(query: SymptomQuery) -> Recommendation:
    # Trace
    trace_id = query.trace_id or new_trace_id()
    query.trace_id = trace_id

    observer.log(trace_id, "received_query", {"query": query.model_dump()})

    # Location normalization
    location_norm = ensure_location_known(query.location)
    observer.log(trace_id, "normalized_location", {"location": location_norm})

    # Specialty classification
    specialty = classify_specialty(query.symptoms)
    observer.log(trace_id, "classified_specialty", {"specialty": specialty})

    # Simulated tools (centers and pharmacies)
    centers = tool_search_centers(specialty, location_norm, k=3)
    pharmacies = tool_search_pharmacies(location_norm, k=3)
    observer.log(trace_id, "tools_results", {"centers": centers, "pharmacies": pharmacies})

    # LLM narrative (local stub)
    message = llm_generate_narrative(query.symptoms, specialty, location_norm)
    observer.log(trace_id, "llm_narrative", {"message": message})

    # Build recommendation
    rec = Recommendation(
        specialty=specialty,
        centers=centers,
        pharmacies=pharmacies,
        message=message,
        trace_id=trace_id
    )

    # Save in session memory and memory bank
    session_record = {"input": query.model_dump(), "output": rec.model_dump()}
    session_service.save(query.user_id, session_record)

    memory_bank.add(MemoryRecord(
        timestamp=now_iso(),
        trace_id=trace_id,
        input=query.model_dump(),
        output=rec.model_dump()
    ))

    observer.log(trace_id, "final_recommendation", {"recommendation": rec.model_dump()})
    return rec

