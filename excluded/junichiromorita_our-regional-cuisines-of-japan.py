def text_gen(prompt: str, token_limit=token_limit) -> str:
    """
    Generate a response using the Gemma model.
    
    Args:
        prompt (str): The input prompt for the model.
    
    Returns:
        str: The generated response from the model.
    """
    try:
        tick()
        input_text = f"<start_of_turn>user\n次の指示に対する回答を作成してください。\n{prompt}<end_of_turn>\n<start_of_turn>model\n"
        output = gemma_lm.generate(input_text, max_length=token_limit)
        #print("\nGemma output:")
        #print(output)
        tock()
        return output or "Error: No output generated by the model."  # Return default message if None
    except Exception as e:
        #print(f"Error during text generation: {e}")
        return "Error: Model failed to generate output."


