import keras
import keras_nlp
import datasets
from datasets import load_dataset
import re

tokenizer = keras_nlp.models.GemmaTokenizer.from_preset(model_id)

def extract_cuisine_and_history(md_content):
    # Extract cuisine name (supports both English and Japanese)
    cuisine_match = re.search(r"\*\*Cuisine Name\*\*: (.*?)\n|\*\*郷土料理名\*\*: (.*?)\n", md_content)
    cuisine_name = cuisine_match.group(1) or cuisine_match.group(2) if cuisine_match else None

    # Extract history information (supports both English and Japanese)
    history_match = re.search(
        r"## History, Origin, and Related Events\n(.*?)(\n##|\Z)|## 歴史・由来・関連行事\n(.*?)(\n##|\Z)", 
        md_content, 
        re.S
    )
    history_text = history_match.group(1) or history_match.group(3) if history_match else None

    return cuisine_name, history_text

# Loading the datasets
dataset = load_dataset('JunichiroMorita/Our-Regional-Cuisines', data_files='our_regional_cuisines_jpn.csv')

# Convert dataset into Instructions and Answer format
def format_dataset(example):
    cuisine_name, history_text = extract_cuisine_and_history(example["text"])
    # Always return a dictionary
    return {
        "Instructions": f"{cuisine_name}の歴史・由来・関連行事について説明してください。" if cuisine_name else "",
        "Answer": history_text if history_text else ""
    }

# Transform dataset
formatted_data = dataset["train"].map(
    format_dataset, 
    remove_columns=["text"],  # Remove the original column
    batched=False
)

# Filter out invalid rows (where Instructions or Answer is None)
ds = formatted_data.filter(lambda x: x["Instructions"] and x["Answer"])
print(ds)
data = ds.with_format("np", columns=["Instructions", "Answer"], output_all_columns=False)
train = []

for x in data:
  item = f"<start_of_turn>user\n次の指示に対する回答を作成してください。\n{x['Instructions']}<end_of_turn>\n<start_of_turn>model\n{x['Answer']}<end_of_turn>"
  length = len(tokenizer(item))
  # skip data if the token length is longer than our limit
  if length < token_limit:
    train.append(item)
    if(len(train)>=num_data_limit):
      break

print('Example of Dataset:\n',train[0], '\n')
print('Example of Dataset:\n',train[1], '\n')
print('Example of Dataset:\n',train[2], '\n')


# Enable LoRA for the model and set the LoRA rank to 'lora_rank'.
gemma_lm.backbone.enable_lora(rank=lora_rank)
gemma_lm.summary()

# Limit the input sequence length (to control memory usage).
gemma_lm.preprocessor.sequence_length = token_limit
# Use AdamW (a common optimizer for transformer models).
optimizer = keras.optimizers.AdamW(
    learning_rate=lr_value,
    weight_decay=0.01,
)
# Exclude layernorm and bias terms from decay.
optimizer.exclude_from_weight_decay(var_names=["bias", "scale"])

gemma_lm.compile(
    loss=keras.losses.SparseCategoricalCrossentropy(from_logits=True),
    optimizer=optimizer,
    weighted_metrics=[keras.metrics.SparseCategoricalAccuracy()],
)


class CustomCallback(keras.callbacks.Callback):
  def on_epoch_end(self, epoch, logs=None):
    model_name = f"/kaggle/working/{lora_name}_{lora_rank}_epoch{epoch+1}.lora.h5"
    gemma_lm.backbone.save_lora_weights(model_name)

    # Evaluate
    response = text_gen("天ぷらの歴史・由来・関連行事について説明してください。")
    print(response)

history = gemma_lm.fit(train, epochs=train_epoch, batch_size=1, callbacks=[CustomCallback()])

import matplotlib.pyplot as plt
plt.plot(history.history['loss'])
plt.show()


