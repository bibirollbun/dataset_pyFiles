# Feature engineering for date

def date_feature_engineering(df):
    """
    Performs feature engineering on a date column in the given DataFrame.
    Adds various date-related features to the DataFrame.

    Args:
        df (pd.DataFrame): DataFrame containing a 'date' column.

    Returns:
        pd.DataFrame: DataFrame with additional date features.
    """
    df['date'] = pd.to_datetime(df['date'])
    df['Year'] = df['date'].dt.year
    df['Quarter'] = df['date'].dt.quarter
    df['Month'] = df['date'].dt.month
    df['Day'] = df['date'].dt.day
    df['day_of_week'] = df['date'].dt.dayofweek
    df['week_of_year'] = df['date'].dt.isocalendar().week

    # Cyclical Features
    df['day_sin'] = np.sin(2 * np.pi * df['Day'] / 31.0)
    df['day_cos'] = np.cos(2 * np.pi * df['Day'] / 31.0)
    df['month_sin'] = np.sin(2 * np.pi * df['Month'] / 12.0)
    df['month_cos'] = np.cos(2 * np.pi * df['Month'] / 12.0)
    
    return df


# Apply feature engineering to both train and test data
train = date_feature_engineering(train)
test = date_feature_engineering(test)


## Lag Features and Rolling Aggregates
def add_lag_rolling_features(df, target_col, lags, rollings):
    for lag in lags:
        df[f'lag_{lag}'] = df[target_col].shift(lag)
    for rolling in rollings:
        df[f'rolling_mean_{rolling}'] = df[target_col].shift(1).rolling(window=rolling).mean()
        df[f'rolling_std_{rolling}'] = df[target_col].shift(1).rolling(window=rolling).std()
    return df



# Apply lag and rolling features to train
