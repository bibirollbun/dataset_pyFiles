# --- AGENT 1: THE NAVIGATOR AGENT (Creative Planning) ---
def navigator_agent(city: str, interests: str) -> dict:
    """
    First agent in the sequence. Fetches attractions and sets the initial state (Memory).
    """
    print(f"\n[AGENT 1: NAVIGATOR] Starting task: Finding top attractions for {city} based on {interests}...")
    
    # 1. Navigator Agent uses its Tool
    attractions_str = search_attractions(city, interests)
    attractions_list = [a.strip() for a in attractions_str.split(',')]
    
    # 2. Navigator Agent sets the shared state/memory for the next agent
    trip_state = {
        'city': city,
        'interests': interests,
        # This list is the 'memory' passed to Agent 2
        'chosen_attractions': attractions_list 
    }
    
    print(f"[AGENT 1: NAVIGATOR] Finished. Passing {len(attractions_list)} attractions to Logistics Agent.")
    return trip_state


