# Imports & simple config
import json
import os
from datetime import datetime
from typing import List, Dict, Optional
import logging
import requests  # Kaggle environment has requests

LOG = logging.getLogger("task_concierge")
LOG.setLevel(logging.INFO)
if not LOG.handlers:
    ch = logging.StreamHandler()
    LOG.addHandler(ch)

# Configuration
TASKS_FILE = "tasks.json"  # persistent memory
USE_WEATHER_TOOL = True    # toggle web tool demo (no API key needed)



# Memory manager (JSON)
class MemoryManager:
    def __init__(self, path: str = TASKS_FILE):
        self.path = path
        if not os.path.exists(self.path):
            self._write({"tasks": []})

    def _read(self):
        with open(self.path, "r") as f:
            return json.load(f)

    def _write(self, data):
        with open(self.path, "w") as f:
            json.dump(data, f, indent=2)

    def add_task(self, task: Dict):
        data = self._read()
        data["tasks"].append(task)
        self._write(data)
        LOG.info(f"Task added: {task['title']}")

    def list_tasks(self):
        data = self._read()
        return data.get("tasks", [])

    def clear_tasks(self):
        self._write({"tasks": []})
        LOG.info("All tasks cleared.")



# Simple planner and summary agents
class PlannerAgent:
    def __init__(self, memory: MemoryManager):
        self.memory = memory

    def add_task(self, title: str, category: str = "personal", due: Optional[str] = None, priority: int = 3):
        task = {
            "title": title,
            "category": category.lower(),
            "due": due,
            "priority": int(priority),
            "created_at": datetime.utcnow().isoformat() + "Z"
        }
        self.memory.add_task(task)
        return {"status": "ok", "task": task}

class SummaryAgent:
    def __init__(self, memory: MemoryManager):
        self.memory = memory

    def _prioritize(self, tasks: List[Dict]) -> List[Dict]:
        # simple sort: (priority asc, due earliest first)
        def due_key(t):
            if t.get("due"):
                try:
                    return datetime.fromisoformat(t["due"])
                except Exception:
                    return datetime.max
            return datetime.max
        return sorted(tasks, key=lambda t: (t.get("priority", 3), due_key(t)))

    def generate_daily_summary(self, include_weather: bool = False) -> str:
        tasks = self.memory.list_tasks()
        if not tasks:
            return "You have no tasks for today. Enjoy your free time!"

        prioritized = self._prioritize(tasks)
        lines = ["Daily Plan — Generated by Daily Task Concierge Agent", f"Generated at: {datetime.utcnow().isoformat()}Z", ""]
        for idx, t in enumerate(prioritized, start=1):
            due = f" (due {t['due']})" if t.get("due") else ""
            lines.append(f"{idx}. [{t.get('category','')}] {t['title']}{due} — priority {t.get('priority',3)}")

        if include_weather and USE_WEATHER_TOOL:
            weather_line = fetch_weather_note()
            if weather_line:
                lines.append("")
                lines.append(weather_line)

        return "\n".join(lines)



# Optional small tool - fetch today's weather (public endpoint, no key)
def fetch_weather_note(lat: float = 12.9716, lon: float = 77.5946):
    """
    Default coordinates: Bangalore, India.
    Uses open-meteo.com to fetch current weather summary (no API key needed).
    """
    try:
        url = f"https://api.open-meteo.com/v1/forecast?latitude={lat}&longitude={lon}&current_weather=true&timezone=UTC"
        r = requests.get(url, timeout=5)
        r.raise_for_status()
        data = r.json()
        cw = data.get("current_weather", {})
        temp = cw.get("temperature")
        wind = cw.get("windspeed")
        weather_line = f"Weather note: Current temp {temp}°C, wind {wind} m/s (data: open-meteo)."
        LOG.info("Weather fetched via web tool.")
        return weather_line
    except Exception as e:
        LOG.warning(f"Weather fetch failed: {e}")
        return None



