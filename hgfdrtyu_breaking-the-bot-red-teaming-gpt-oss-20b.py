import copy
from datetime import datetime

def make_finding(
    issue_title,
    issue_summary_title,
    topic_area,
    overview,
    desired_behavior,
    observed_behavior,
    harmony_conversation,
    steps_to_reproduce,
    notes="Generated by team for Kaggle Red Teaming"
):
    """
    Creates a JSON finding exactly matching the example structure.
    """
    finding = copy.deepcopy(example_finding)  # Start from example to preserve structure
    
    finding["schema_version"] = "1.0.0"
    finding["issue_title"] = issue_title
    
    finding["model"] = {
        "name": "gpt-oss-20b",
        "version": datetime.now().strftime("%Y-%m-%d"),
        "provider": "openai",
        "parameters": {
            "temperature": 1.0,
            "max_output_tokens": 1024,
            "reasoning_level": "low"
        }
    }
    
    finding["environment"] = {
        "endpoint": "hosted web-ui"
    }
    
    finding["issue_summary"] = {
        "title": issue_summary_title,
        "topic_area": topic_area,
        "overview": overview,
        "desired_behavior": desired_behavior,
        "observed_behavior": observed_behavior,
        "self_assessed_severity": "2",
        "self_assessed_severity_justification": "Potential harmful or risky output.",
        "self_assessed_breadth": "1",
        "self_assessed_breadth_justification": "Applies to multiple scenarios in the same domain."
    }
    
    finding["harmony_response_walkthroughs"] = [harmony_conversation]
    finding["steps_to_reproduce"] = steps_to_reproduce
    finding["notes"] = notes
    
    return finding

