def get_score(filename):
    # Handles "0.70366_submission_3.csv" -> 0.70366
    # Handles "0.64020_submission.csv"   -> 0.64020
    try:
        return float(filename.split('_')[0])
    except:
        return 0.0

all_files = [
    f for f in os.listdir(INPUT_PATH) 
    if f.endswith('.csv') and 'noscore' not in f
]

# Sort High -> Low
all_files.sort(key=get_score, reverse=True)

print(f"Total candidate files: {len(all_files)}")


# We want 7 files that are high scoring but NOT identical.
TARGET_COL = 'diagnosed_diabetes' # The column we are blending
ID_COL = 'id'

selected_files = []
selected_dfs = [] # Store dataframes to check correlation

# Limit candidates to top 25 to save memory/time
candidates = all_files[:25]

print("\nStarting Diversity Check (Correlation Pruning)...")

for filename in candidates:
    # Read the file
    filepath = os.path.join(INPUT_PATH, filename)
    df_curr = pd.read_csv(filepath)
    
    # Check correlation with ALREADY selected files
    is_too_similar = False
    for df_prev in selected_dfs:
        # Calculate correlation score (1.0 = identical, 0.0 = different)
        corr = df_curr[TARGET_COL].corr(df_prev[TARGET_COL])
        
        # Threshold: 0.995. If higher, it's basically the same submission.
        if corr > 0.995:
            is_too_similar = True
            break
            
    # Selection Logic:
    # Always take the very first (best) file.
    # For others, take them ONLY if they are distinct (not too similar).
    if len(selected_files) == 0:
        selected_files.append(filename)
        selected_dfs.append(df_curr)
        print(f"Selected Anchor (Best): {filename}")
        
    elif not is_too_similar:
        selected_files.append(filename)
        selected_dfs.append(df_curr)
        print(f"Selected Diverse:       {filename}")
    else:
        print(f"Skipped (Duplicate):    {filename}")
    
    # Stop once we have 7
    
    # if len(selected_files) >= 7:
    if len(selected_files) >= 4:
        break

# Fallback: If we didn't find 7 unique files, fill up with the next best remaining files

