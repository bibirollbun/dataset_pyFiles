ATCHLEY_ARRAY = np.array([ATCHLEY_FACTORS.get(aa, [0, 0, 0, 0, 0]) for aa in 'ACDEFGHIKLMNPQRSTVWY'])
AA_TO_INDEX = {aa: i for i, aa in enumerate('ACDEFGHIKLMNPQRSTVWY')}

# AI-generated, human-optimized (otherwise would be too slow)
def encode_atchley_kmer(sequence, k=4, normalize=True):
    seq_len = len(sequence)
    n_kmers = seq_len - k + 1
    if n_kmers <= 0:
        return np.zeros(5)
    kmer_features = np.zeros((n_kmers, 5))
    valid_count = 0
    for i in range(n_kmers):
        kmer = sequence[i:i+k]
        try:
            indices = [AA_TO_INDEX[aa] for aa in kmer]
            kmer_features[valid_count] = ATCHLEY_ARRAY[indices].mean(axis=0)
            valid_count += 1
        except KeyError:
            continue
    if valid_count == 0:
        return np.zeros(5)
    result = kmer_features[:valid_count].mean(axis=0)
    if normalize:
        norm = np.linalg.norm(result)
        if norm > 0:
            result /= norm
    return result


def gene_split(column=None):
    return column.str.split('-', expand=True)
    
def gene_cleaning(column=None, target='j'):
    return column.str.strip('TCRB' + target.upper())
    
def process_sequencing_file(df, targets=['v', 'j', 'd']):
    # for AtchleyKmerEncoder, you have to choose k-mer length 
    # I am going to partially copy this paper: https://pmc.ncbi.nlm.nih.gov/articles/PMC7993519/
    # It uses one-hot encoded V/J/D genes + 4-kmer encoded Junctions
    # I am not going to skip any AA's from start or end bc I wasn't able to find any evidence it makes sense with CDR3 beta 
    #atchley(k_mer=4, abundance=RELATIVE_ABUNDANCE, skip_first_n_aa=0,skip_last_n_aa=0, normalize_all_features=False) 
    


    for target in targets:
        column = target + "_call"
        df[column] = gene_cleaning(df[column], target)
        res = gene_split(df[column]) 
        # decided to ignore p3 as it is very rare
        df[column + 'f'], df[column + 's'] = res[0], res[1]
        df = df.drop(columns=[column])

        for item in ['f', 's']:
            df[column + item] = df[column + item].replace('unknown', '0')
            df[column + item] = df[column + item].replace([None], '0')

    
    df['junction_aa'] = df['junction_aa'].apply(encode_atchley_kmer)
    return df


