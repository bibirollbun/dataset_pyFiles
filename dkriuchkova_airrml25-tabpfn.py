# TCR beta CDR3 is the highly variable region of the T-cell receptor's beta chain 
# that is critical for recognizing specific peptide-MHC complexes. 
# It is generated by the imprecise joining of gene segments (V(D)J recombination), 
# resulting in a unique sequence and length for each T-cell clone. 

# These aminoacids then are directly responsible to interact with the MHC + peptide complexes. 
# Therefore if we look at correlation of TCR beta CDR3 + HLA sequence,
# we can understand if T-cell would bind to cell that exibits HLA sequence,
# without knowing which peptide is exibited (which will introduce noise).

# The sequence is the result of V(D)J recombination, 
# where a V-beta gene segment joins with a D-beta segment (in some cases) 
# and then a J-beta gene segment, with the exact length and amino acid sequence 
# being determined by the specific segments chosen and the junctional diversity 
# that occurs during the process.


