# 3. ROBUST AGENT FRAMEWORK
# ------------------------------------------------------------------

class ADKAgent:
    def __init__(self, name: str, model_name: str, instructions: str, tools: list = []):
        self.name = name
        self.model_name = model_name

        # You can relax/tune these if you want
        self.safety_settings = [
            {"category": "HARM_CATEGORY_HARASSMENT", "threshold": "BLOCK_NONE"},
            {"category": "HARM_CATEGORY_HATE_SPEECH", "threshold": "BLOCK_NONE"},
            {"category": "HARM_CATEGORY_SEXUALLY_EXPLICIT", "threshold": "BLOCK_NONE"},
            {"category": "HARM_CATEGORY_DANGEROUS_CONTENT", "threshold": "BLOCK_NONE"},
        ]

        try:
            self.model = genai.GenerativeModel(
                model_name=model_name,
                tools=tools,
                system_instruction=instructions,
                safety_settings=self.safety_settings,
            )
            self.chat = self.model.start_chat(enable_automatic_function_calling=True)
        except Exception as e:
            print(f"âš ï¸� Error initializing model {model_name}: {e}")
            self.chat = None

    def run(self, input_text: str):
        if not self.chat:
            return "âš ï¸� Agent not initialized."

        log_trace(self.name, "Received Task", input_text)

        try:
            response = self.chat.send_message(input_text)

            # Robust handling of tool calls / empty parts
            if hasattr(response, "parts") and response.parts:
                output = response.text
            elif getattr(response, "candidates", None):
                cand = response.candidates[0]
                if cand.content and cand.content.parts:
                    output = "Task completed (Tool Executed)."
                else:
                    output = "âš ï¸� Error: Empty response from model (Safety or Tool Error)."
            else:
                output = "âš ï¸� Error: Empty response from model."

            log_trace(self.name, "Completed", output)
            return output

        except ResourceExhausted:
            return "âš ï¸� Quota exceeded. Please try again later."
        except NotFound:
            return f"âš ï¸� Error: Model '{self.model_name}' not found. Check API availability."
        except Exception as e:
            return f"âš ï¸� Runtime Error: {str(e)}"

