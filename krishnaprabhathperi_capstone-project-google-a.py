MODEL_VERSION = "gemini-2.5-flash-lite"   # change to gemini-2.5-flash if you prefer

def run_content_studio(topic: str):
    print(f"ğŸš€ Starting Content Studio using {MODEL_VERSION} for topic: '{topic}'\n" + "="*60)

    # 1. Researcher
    researcher = ADKAgent(
        "Researcher",
        MODEL_VERSION,
        "You are a Senior Technical Researcher. Use google_search_tool to find facts. "
        "Always call the tool. Output a concise bullet summary.",
        [google_search_tool],
    )

    # 2. Drafter
    drafter = ADKAgent(
        "Drafter",
        MODEL_VERSION,
        "You are a Technical Writer. Take the research notes and write a concise, "
        "professional technical blog post. Use format_to_markdown_tool on your final draft.",
        [format_to_markdown_tool],
    )

    # 3. Critic
    critic = ADKAgent(
        "Critic",
        MODEL_VERSION,
        "You are a Chief Editor. Review the draft for clarity, tone, and accuracy. "
        "If the draft is good, reply with 'APPROVED' followed by the final text. "
        "If it needs changes, list specific feedback.",
        [],
    )

    # ---- Step 1: Research ----
    print("\nğŸ”� Step 1: Researching...")
    research_prompt = f"Find key technical details and recent news about: {topic}"
    research_output = researcher.run(research_prompt)
    display(Markdown(f"### Research Summary\n{research_output}"))

    # ---- Step 2: Drafting ----
    print("\nâœ�ï¸� Step 2: Drafting...")
    draft_input = (
        f"Here is the research:\n{research_output}\n\n"
        f"Write a technical blog post about this. At the end, call format_to_markdown_tool "
        f"to format the final blog post."
    )
    draft_output = drafter.run(draft_input)

    # ---- Step 3: Critiquing ----
    print("\nğŸ§� Step 3: Critiquing...")
    critic_input = (
        f"Here is the research:\n{research_output}\n\n"
        f"Here is the draft:\n{draft_output}\n\n"
        f"Critique this. Remember: if it is good enough, respond with 'APPROVED' "
        f"followed by the final text."
    )
    critic_output = critic.run(critic_input)

    # ---- Final Output ----
    print("\n" + "="*60 + "\nâœ… FINAL OUTPUT\n" + "="*60)
    if "APPROVED" in critic_output:
        # If the critic inlines the final text, show that;
        # otherwise, show the draft (since it likely contains the markdown).
        display(Markdown(draft_output))
    else:
        display(
            Markdown(
                f"### Editor Feedback\n{critic_output}\n\n"
                f"---\n\n### Latest Draft\n{draft_output}"
            )
        )

    # ---- Observability Trace ----
    print("\nğŸ“Š Observability Trace Log:")
    for log in TRACE_LOG:
        print(log)

