# Orchestrator and agent router for LexGuard

class Supervisor:
    """Top-level controller that manages agents, tools, memory, and logs."""
    def __init__(self, settings: Dict, tools: Tool, memory: MemoryUnit, logger: LogManager):
        self.settings = settings
        self.tools = tools
        self.memory = memory
        self.logger = logger
        self.model = genai.GenerativeModel(model_name=settings["model"], tools=[tools])
        self.metrics = {
            "requests": 0,
            "tool_calls": 0,
            "avg_latency": 0.0,
            "errors": 0
        }
        self.logger.info("Supervisor created", model=settings["model"])

    def _call_tool(self, function_call) -> Any:
        """Execute a registered tool (function)."""
        fname = function_call.name
        args = dict(function_call.args)
        self.logger.info("Tool invocation", tool=fname, args=str(args))
        self.metrics["tool_calls"] += 1

        # Local mapping: name -> python function
        local_map = {
            "split_into_clauses": split_into_clauses,
            "validate_standards": validate_standards,
            "flag_risk_elements": flag_risk_elements,
            # rewrite and summary will be called directly via LLM when needed
        }

        if fname in local_map:
            try:
                return local_map[fname](**args)
            except Exception as e:
                self.logger.error("Tool error", tool=fname, error=str(e))
                self.metrics["errors"] += 1
                return {"error": str(e)}
        else:
            self.logger.error("Unknown tool", tool=fname)
            return {"error": f"Unknown tool {fname}"}

    def analyze_document(self, doc_text: str, use_llm_rewrite: bool = True) -> Dict:
        """High-level pipeline for analyzing a contract text."""
        t0 = time.time()
        self.metrics["requests"] += 1
        self.memory.store("user", f"Analyze document ({len(doc_text)} chars)")

        # Step 1: Clause segmentation (tool)
        try:
            clause_result = split_into_clauses(doc_text)
            clauses = clause_result.get("clauses", [])
            count = clause_result.get("count", len(clauses))
            self.logger.info("Segmentation complete", clauses_extracted=count)
        except Exception as e:
            self.logger.error("Segmentation failed", error=str(e))
            clauses, count = [], 0

        # Step 2: Policy validation (tool)
        try:
            validation = validate_standards(clauses)
            missing = validation.get("missing_items", [])
            self.logger.info("Validation complete", missing_count=len(missing))
        except Exception as e:
            self.logger.error("Validation failed", error=str(e))
            missing = []

        # Step 3: Risk flagging (tool)
        try:
            flagged = flag_risk_elements(clauses)
            risks = flagged.get("risky_clauses", [])
            self.logger.info("Risk detection complete", risk_count=len(risks))
        except Exception as e:
            self.logger.error("Risk detection failed", error=str(e))
            risks = []

        # Optional Step 4: Clause enhancement (LLM)
        enhanced = {}
        if use_llm_rewrite and (missing or risks):
            self.logger.info("Starting clause enhancement", missing=len(missing), risks=len(risks))
            # For demonstration, rewrite first risky clause and propose a missing clause template
            sample_rewrites = {}
            try:
                if risks:
                    sample_rewrites["rewrite_example"] = enhance_clause(risks[0])
                if missing:
                    template_prompt = f"Provide a concise, enterprise-grade template for the clause: {missing[0]}"
                    model = genai.GenerativeModel(self.settings["model"])
                    sample_rewrites["missing_example"] = model.generate_content(template_prompt).text
                enhanced = sample_rewrites
                self.logger.info("Enhancement complete", items=len(sample_rewrites))
            except Exception as e:
                self.logger.error("Enhancement error", error=str(e))

        # Step 5: Assemble results
        summary = {
            "count": count,
            "missing": missing,
            "risks": risks,
            "enhanced": enhanced
        }

        # Step 6: Generate final textual summary (local)
        report_text = build_summary(summary)
        elapsed = time.time() - t0
        # update running average latency
        prev = self.metrics["avg_latency"]
        n = self.metrics["requests"]
        self.metrics["avg_latency"] = ((prev * (n - 1)) + elapsed) / n
        self.memory.store("agent", f"Analysis complete (time: {elapsed:.2f}s)")
        self.logger.info("Analysis finished", latency=f"{elapsed:.2f}s")
        return {"report": report_text, "summary": summary, "latency": elapsed}

    def get_metrics(self) -> Dict:
        stats = {
            **self.metrics,
            "memory": {"entries": len(self.memory.history), "recent": self.memory.recent()},
            "logs": {"entries": len(logger.logs)}
        }
        return stats

    def reset(self):
        self.memory.history.clear()
        self.metrics = {"requests": 0, "tool_calls": 0, "avg_latency": 0.0, "errors": 0}
        self.logger.info("Supervisor reset")



