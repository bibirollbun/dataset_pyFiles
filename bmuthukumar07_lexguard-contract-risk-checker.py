def split_into_clauses(text: str):
    """Basic segmentation of contract text."""
    lines = [l.strip() for l in text.split("\n") if l.strip()]
    clauses = [l for l in lines if len(l.split()) > 4]
    return {"clauses": clauses, "count": len(clauses)}

def validate_standards(clauses: List[str]):
    """Check clauses against policy standards."""
    standards = [
        "Confidentiality", "Liability", "Termination", "Governing Law",
        "Payment Terms", "Indemnification"
    ]
    missing = [std for std in standards if not any(std.lower() in c.lower() for c in clauses)]
    return {"missing_items": missing}

def flag_risk_elements(clauses: List[str]):
    """Detect risky or uncertain language."""
    risky = ["unlimited", "sole responsibility", "may terminate without notice"]
    flagged = [c for c in clauses if any(r in c.lower() for r in risky)]
    return {"risky_clauses": flagged}

def enhance_clause(weak_clause: str):
    """Use LLM to strengthen a clause."""
    model = genai.GenerativeModel(SETTINGS["model"])
    prompt = (
        f"Improve this legal clause for clarity and compliance:\n\n{weak_clause}\n\n"
        "Provide a polished, strong version."
    )
    return model.generate_content(prompt).text

