def save_conversation(filename="lexguard_conversation.txt"):
    try:
        with open(filename, "w") as f:
            f.write("LEXGUARD CONVERSATION LOG\n")
            f.write("="*60 + "\n\n")
            for msg in memory.history:
                f.write(f"[{msg['time']}] {msg['role'].upper()}:\n{msg['content']}\n\n")
        print(f"✓ Conversation saved: {filename}")
        return filename
    except Exception as e:
        print("❌ Save failed:", e)
        return None

def save_logs(filename="lexguard_logs.json"):
    try:
        with open(filename, "w") as f:
            json.dump(logger.logs, f, indent=2)
        print(f"✓ Logs saved: {filename}")
        return filename
    except Exception as e:
        print("❌ Save failed:", e)
        return None

