@dataclass
class MemoryUnit:
    history: List[Dict[str, str]] = field(default_factory=list)
    capacity: int = 20
    
    def store(self, role, text):
        self.history.append({"role": role, "content": text, "time": datetime.now().isoformat()})
        if len(self.history) > self.capacity:
            self.history = self.history[-self.capacity:]
    
    def recent(self):
        return "\n".join([f"{m['role']}: {m['content'][:80]}..." for m in self.history[-5:]])



@dataclass
class LogManager:
    logs: List[Dict] = field(default_factory=list)
    
    def write(self, level, event, **details):
        self.logs.append({
            "time": datetime.now().isoformat(),
            "level": level,
            "event": event,
            "details": details
        })
    
    def info(self, event, **details): self.write("INFO", event, **details)
    def error(self, event, **details): self.write("ERROR", event, **details)

