# DATAFRAME

df=pd.read_csv("/kaggle/input/playground-series-s5e2/train.csv")
print(df.head(10))


print(df.info())
print(df.isnull().sum())
print(df.describe())


#FUNCTION TO RETURN THE NUMBER OF UNIQUE VALUES IN A COLUMN
def unique_value_count(df, column_name):
   
    unique_values = df[column_name].nunique()
    print(f"Column '{column_name}' has {unique_values} unique values.")
    return unique_values



unique_value_count(df, "Color")
unique_value_count(df, "Brand")
unique_value_count(df, "Material")
unique_value_count(df, "Size")
unique_value_count(df, "Laptop Compartment")
unique_value_count(df, "Waterproof")
unique_value_count(df, "Style")
unique_value_count(df, "Weight Capacity (kg)")




#Fill Missing values

categorical_cols = ["Color", "Brand", "Material", "Size", "Laptop Compartment", "Waterproof", "Style"]
for col in categorical_cols:
    df[col] = df[col].fillna(df[col].mode()[0])



df["Weight Capacity (kg)"] = df["Weight Capacity (kg)"].fillna(df["Weight Capacity (kg)"].median())




#Label ENcoding

le = LabelEncoder()
for col in categorical_cols:
    df[col] = le.fit_transform(df[col])


label_encoders = {}

for col in categorical_cols:
    le = LabelEncoder()
    df[col] = le.fit_transform(df[col])  # Fit on training data
    label_encoders[col] = dict(zip(le.classes_, le.transform(le.classes_)))  # Store mapping
    label_encoders[col]["Unknown"] = -1  # Assign unknown categories a default value




#Splitting Data for Training & Testing

x=df.drop(columns=["Price"])
y=df["Price"]


# Train the Model
from sklearn.model_selection import RandomizedSearchCV
import xgboost as xgb
param_dist = {
    "n_estimators": [100, 300, 500, 700],
    "learning_rate": [0.01, 0.05, 0.1, 0.2],
    "max_depth": [3, 5, 7, 10],
    "subsample": [0.6, 0.8, 1.0],
    "colsample_bytree": [0.6, 0.8, 1.0],
    "gamma": [0, 0.1, 0.2, 0.3]
}



dt_model=xgb.XGBRegressor(n_estimators=300, learning_rate=0.05, max_depth=5, random_state=42)

search = RandomizedSearchCV(dt_model, param_dist, n_iter=10, cv=5, scoring="neg_mean_absolute_error", random_state=42)


search.fit(x,y)


print("Best Parameters:", search.best_params_)

best_model = xgb.XGBRegressor(**search.best_params_, random_state=42,tree_method="gpu_hist")
best_model.fit(x,y)




#Preprocessing Test dataset
 
df_test = pd.read_csv("/kaggle/input/playground-series-s5e2/test.csv")


categorical_cols = ["Color", "Brand", "Material", "Size", "Laptop Compartment", "Waterproof", "Style"]
for col in categorical_cols:
    df_test[col] = df_test[col].map(label_encoders[col]).fillna(-1).astype(int)


df_test["Weight Capacity (kg)"] = df_test["Weight Capacity (kg)"].fillna(df_test["Weight Capacity (kg)"].median())

le = LabelEncoder()
for col in categorical_cols:
    df_test[col] = le.fit_transform(df_test[col])


x_test=df_test




#Prediction
y_pred = best_model.predict(x_test)



#Evaluate Performance (On Training Data)

from sklearn.metrics import mean_absolute_error, mean_squared_error

y_train_pred = best_model.predict(x)

mae = mean_absolute_error(y, y_train_pred)
mse = mean_squared_error(y, y_train_pred)
rmse = mse ** 0.5

print(f"Mean Absolute Error (MAE): {mae}")
print(f"Root Mean Squared Error (RMSE): {rmse}")





