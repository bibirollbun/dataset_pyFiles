# -----------------------------
#  Local LLM Simulator
# -----------------------------
import random

def local_llm(prompt):
    """
    This is a simple local large-language-model simulator.
    It generates deterministic, structured outputs based on patterns.
    This way the multi-agent system works offline without needing any API.
    """

    # Simple deterministic responses based on keywords
    if "plan" in prompt.lower():
        return (
            "1. Understand the project goal.\n"
            "2. Collect requirements and constraints.\n"
            "3. Design the system architecture.\n"
            "4. Implement each module.\n"
            "5. Test, evaluate, and refine.\n"
        )

    if "research" in prompt.lower():
        return (
            "Key research insights:\n"
            "- AI agents can collaborate to solve tasks.\n"
            "- Memory improves long-term reasoning.\n"
            "- Tools allow agents to execute code.\n"
            "- Modular design increases flexibility.\n"
        )

    if "code" in prompt.lower():
        return (
            "Here is example Python code:\n"
            "def greet(name):\n"
            "    return f'Hello, {name}! This was generated by a local AI agent.'\n"
            "\n"
            "print(greet('Capstone Student'))\n"
        )

    # General fallback text
    return "Local AI response: " + " ".join(prompt.split()[:30])


# ============================================================
#  Session Memory
# ============================================================
class Memory:
    def __init__(self):
        self.logs = []

    def add(self, text):
        self.logs.append(text)

    def search(self, key):
        return [x for x in self.logs if key.lower() in x.lower()]


# ============================================================
# Tools (Math, Python Exec, File Writer)
# ============================================================
class Tools:
    def python_exec(self, code):
        try:
            env = {}
            exec(code, {}, env)
            return env
        except Exception as e:
            return {"error": str(e)}

    def math(self, expr):
        try:
            return eval(expr)
        except:
            return "Math error"

    def write_file(self, filename, content):
        try:
            with open(filename, "w") as f:
                f.write(content)
            return f"Saved to {filename}"
        except Exception as e:
            return f"File write error: {str(e)}"


# ============================================================
# A24 Protocol
# ============================================================
def A24(sender, receiver, message):
    return {
        "protocol": "A24",
        "from": sender,
        "to": receiver,
        "content": message
    }


# ============================================================
# Base Agent
# ============================================================
class Agent:
    def __init__(self, name, memory, tools):
        self.name = name
        self.memory = memory
        self.tools = tools

    def think(self, message):
        self.memory.add(f"[{self.name} RECEIVED] {message}")
        response = local_llm(message)
        self.memory.add(f"[{self.name} RESPONSE] {response}")
        return response


# ============================================================
# Specialized Agents
# ============================================================
class PlannerAgent(Agent):
    def plan(self, goal):
        return self.think(f"Create a plan for: {goal}")


class ResearchAgent(Agent):
    def research(self, goal):
        return self.think(f"Research information about: {goal}")


class EngineerAgent(Agent):
    def write_code(self, goal):
        return self.think(f"Write code for: {goal}")


# ============================================================
# Multi-Agent System
# ============================================================
class MultiAgentSystem:
    def __init__(self):
        self.memory = Memory()
        self.tools = Tools()

        self.planner = PlannerAgent("Planner", self.memory, self.tools)
        self.researcher = ResearchAgent("Researcher", self.memory, self.tools)
        self.engineer = EngineerAgent("Engineer", self.memory, self.tools)

    def run(self, goal):
        print("=== STEP 1: PLANNING ===")
        plan = self.planner.plan(goal)
        print(plan)

        print("\n=== STEP 2: RESEARCH ===")
        research = self.researcher.research(goal)
        print(research)

        print("\n=== STEP 3: CODE GEN ===")
        code = self.engineer.write_code(goal)
        print(code)

        # Save to file
        self.tools.write_file("generated_ai_code.py", code)

        return {
            "plan": plan,
            "research": research,
            "code": code,
            "memory": self.memory.logs
        }


# ============================================================
# RUN THE SYSTEM
# ============================================================
system = MultiAgentSystem()

goal = "Build a generative AI agent that recommends personalized study plans"

output = system.run(goal)

print("\n========================")
print("FINAL MEMORY LOGS")
print("========================")
for log in output["memory"]:
    print(log)


