import torch
import random
import numpy as np
import pandas as pd
import bitsandbytes as bnb
from tqdm.auto import tqdm
from datasets import Dataset
from accelerate import Accelerator
from torch.utils.data import DataLoader
from peft import PeftModel
from transformers import AutoModelForSequenceClassification, AutoTokenizer, BitsAndBytesConfig, DataCollatorWithPadding, get_scheduler, get_cosine_schedule_with_warmup

model_name = '/kaggle/input/mistral/pytorch/7b-v0.1-hf/1'
accelerator = Accelerator()

print('Setup is done')


test_df = pd.read_csv('/kaggle/input/llm-detect-ai-generated-text/test_essays.csv')
print('Done loading data')


tokenizer = AutoTokenizer.from_pretrained(
        model_name,
        use_fast=True,
        padding_side='left',
        truncation_side='left', # we truncate the START of the essay, so we won't remove the prompt we added!,
    )
tokenizer.pad_token = tokenizer.unk_token

def preprocess_function(df):
    # TODO: ADD MORE PREPROCESSING !!
    df['text'] = df['text'].apply(lambda x: x.strip() + "\n###\nIs the essay generated by AI?")
    return df
    

def tokenize_function(ds):
    return tokenizer(
        ds['text'], 
        padding='max_length', 
        truncation=True, 
        max_length=1024,
        add_special_tokens=True,
    )

def get_preprocessed_dataset(df, is_test=False):
    df = preprocess_function(df)
    ds = Dataset.from_pandas(df)
    ds = ds.map(tokenize_function, batched=True)
    ds.set_format(type=None, columns=[
            'id',
            'input_ids',
            'attention_mask'
        ])
    return ds

with accelerator.main_process_first():
    test_ds = get_preprocessed_dataset(test_df)

print('Done preprocessing')


data_collator = DataCollatorWithPadding(tokenizer=tokenizer, return_tensors='pt')

def collate_function(features, collator):
    labels = [f["generated"] for f in features] if "generated" in features[0] else None # fetching the labels (the score if generated or not)
    tokenized_inputs = [{"input_ids": f["input_ids"], "attention_mask": f["attention_mask"]} for f in features] # fetching the tokenized inputs and attention only
    batch = collator(tokenized_inputs) # apply the default collator
    if labels is not None:
        batch["labels"] = torch.tensor(labels, dtype=torch.float16) # move to 16bit floats
    return batch

test_ds = accelerator.prepare(test_ds)
test_dl = DataLoader(
    test_ds,
    batch_size=1,
    shuffle=False,
    collate_fn=lambda batch: collate_function(batch, data_collator)
)

print('Done defining collator and loader')


bnb_config = BitsAndBytesConfig(
        load_in_4bit=True,
        bnb_4bit_quant_type="nf4",
        bnb_4bit_use_double_quant=True,
        bnb_4bit_compute_dtype=torch.float16
    )


base_model = AutoModelForSequenceClassification.from_pretrained(
    model_name, 
    num_labels=1, 
    quantization_config=bnb_config,
    low_cpu_mem_usage=True,
    device_map="auto"
)

base_model.config.pretraining_tp = 1
base_model.config.pad_token_id = tokenizer.pad_token_id

peft_model_path = '/kaggle/input/finedtuned-peft-2/'

# Apply LoRA
model = PeftModel.from_pretrained(base_model, peft_model_path)
accelerator.wait_for_everyone()
print('Done loading model')


accelerator.wait_for_everyone()
model, test_dl = accelerator.prepare(model, test_dl)

model.eval()
all_predictions = []

progress_bar = tqdm(range(len(test_dl)), disable=not accelerator.is_local_main_process)

for step, batch in enumerate(test_dl):
    with torch.no_grad():
        outputs = model(**batch)

    logits = outputs.logits.reshape(-1)
    predictions = torch.sigmoid(logits)
    predictions = accelerator.gather_for_metrics(predictions)
    predictions = predictions.cpu().numpy().tolist()

    all_predictions.extend(predictions)

    progress_bar.update(1)
progress_bar.close()

result_df = pd.DataFrame()
result_df["id"] = test_df['id']
result_df["generated"] = all_predictions

accelerator.wait_for_everyone()
if accelerator.is_main_process:
    result_df.to_csv('submission.csv', index=False)

