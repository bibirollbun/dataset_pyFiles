# Measure time
from tqdm.auto import tqdm
import time

# Train and test model
def accuracy_fn(y_true, y_pred):
    correct = torch.eq(y_true, y_pred).sum().item()
    acc = (correct / len(y_pred)) * 100
    return acc

# Training loop
epochs = 15
train_loss_list = []
train_accuracy_list = []
test_loss_list= []
test_accuracy_list= []

start_time = time.time()

for epoch in tqdm(range(epochs)):
    ### Training
    model.train() # set model to training mode
    train_loss = 0
    train_acc = 0
    for batch, (X, y) in enumerate(train_dataloader):
        X, y = X.to(device), y.to(device)

        # 1. Forward pass
        y_pred_logits = model(X)

        # 2. Calculate loss (cross entropy loss requires target to be class indices)
        loss = loss_fn(y_pred_logits,y) # y is already class index

        train_loss += loss.item()

        # 3. Optimizer zero grad
        optimizer.zero_grad()

        # 4. Loss backward
        loss.backward()

        # 5. Optimizer step
        optimizer.step()

        # Calculate accuracy
        y_pred_prob = torch.softmax(y_pred_logits, dim=1)
        y_pred = torch.argmax(y_pred_prob, dim=1)
        train_acc += accuracy_fn(y_pred, y)


    # Calculate average train loss and accuracy
    train_loss /= len(train_dataloader)
    train_acc /= len(train_dataloader)
    train_loss_list.append(train_loss)
    train_accuracy_list.append(train_acc)


    ### Testing
    model.eval() # set model to evaluation mode
    test_loss = 0
    test_acc = 0
    with torch.no_grad():
        for X,y in test_dataloader:
            X,y = X.to(device), y.to(device)

            test_pred_logits = model(X)
            loss = loss_fn(test_pred_logits, y) # Calculate loss on test data
            test_loss += loss.item()

            test_pred_prob = torch.softmax(test_pred_logits, dim=1)
            test_pred = torch.argmax(test_pred_prob, dim=1)
            acc = accuracy_fn(y,test_pred) # Calculate accuracy on test data
            test_acc += acc

    # Calculate average loss and accuracy for the epoch
    test_loss /= len(test_dataloader)
    test_acc /= len(test_dataloader)

    test_loss_list.append(test_loss)
    test_accuracy_list.append(test_acc)


    print(f"Epoch: {epoch+1} | Train loss: {train_loss:.5f} | Train acc: {train_acc:.2f}% | Test loss: {test_loss:.5f} | Test acc: {test_acc:.2f}%")

end_time = time.time()
total_time = end_time - start_time
print(f"Total training time: {total_time:.2f} seconds")


